def avatar_image(name: str) -> str:
    info = PEOPLE_INFO.get(name)
    if not info:
        return ""
    path = info[1]
    try:
        encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    except OSError:
        return ""
    mime = "image/png" if path.suffix.lower() == ".png" else "image/svg+xml"
    return f"data:{mime};base64,{encoded}"


